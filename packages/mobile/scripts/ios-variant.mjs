// `capacitor:sync:after` hook (see package.json): after `cap sync ios` has
// written ios/App/App/capacitor.config.json, derive from it the Xcode build
// settings that depend on the variant. On Android, app/build.gradle reads the
// synced config itself; Xcode cannot set a bundle id from a JSON file, so the
// values go through an xcconfig file instead, included by ios/debug.xcconfig
// and ios/release.xcconfig. ios/App/shell-prebuild.sh checks at build time
// that the two files still agree.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

if (process.env.CAPACITOR_PLATFORM_NAME !== "ios") process.exit(0);

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const synced = JSON.parse(readFileSync(join(root, "ios/App/App/capacitor.config.json"), "utf8"));

const appId = synced.appId;
const appName = synced.appName;
const variant = synced.plugins?.ShellInfo?.variant;
const host = synced.server?.url ? new URL(synced.server.url).hostname : undefined;
if (!appId || !appName || !variant || !host) {
  throw new Error("ios/App/App/capacitor.config.json lacks appId, appName, server.url or the variant.");
}

// An xcconfig value runs to the end of the line, and "//" starts a comment:
// none of these may contain either.
for (const value of [appId, appName, variant, host]) {
  if (/[\n\r]|\/\//.test(value)) throw new Error(`Value not representable in an xcconfig file: ${value}`);
}

// The App Store provisioning profile of each bundle id, by its name in the
// Apple Developer account. Only the Release configuration (archives for
// TestFlight and the App Store) signs with it; simulator builds are unsigned.
const PROFILES = {
  "fr.ohmywind.app": "OhMyWind App Store",
  "fr.ohmywind.app.dev": "OhMyWind Dev App Store",
};
const profile = PROFILES[appId];
if (!profile) throw new Error(`No App Store profile known for ${appId}`);

const lines = [
  "// Generated by scripts/ios-variant.mjs at `cap sync ios`. Do not edit.",
  `OHMYWIND_VARIANT = ${variant}`,
  `OHMYWIND_APP_ID = ${appId}`,
  `OHMYWIND_DISPLAY_NAME = ${appName}`,
  `OHMYWIND_APP_BOUND_DOMAIN = ${host}`,
  `OHMYWIND_PROFILE_NAME = ${profile}`,
  "",
];
writeFileSync(join(root, "ios/App/variant.xcconfig"), lines.join("\n"));
console.log(`[ios-variant] ${variant}: ${appId}, "${appName}", app-bound domain ${host}, profile "${profile}"`);
